// --------------------------------------------------------------------- blogs
const toMarkdown = (blocks) =>
  blocks
    .map((b) => {
      if (b.h) return `### ${b.h}`;
      if (b.q) return `> ${b.q}`;
      if (b.ul) return b.ul.map((li) => `- ${li}`).join('\n');
      return b.p;
    })
    .join('\n\n');

emit('-- Blog articles');
