// Generates supabase/seed.sql from the original hard-coded content in
// supabase/seed-data/*.mjs. The app itself never imports those files — after
// seeding, everything is edited from the dashboard.
//
//   node scripts/generate-seed.mjs
//
// Every statement is idempotent (ON CONFLICT DO NOTHING / insert-if-empty), so
// re-running the seed never overwrites content edited in the dashboard.

