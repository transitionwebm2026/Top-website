// Page-specific copy (hero, home, about, prefooter, contact form) moves into
// section content; everything else is static UI text.
const SECTION_OWNED = new Set(['hero', 'home', 'about', 'prefooter']);
const MOVED_KEYS = new Set(['contact.formTitle', 'contact.formDesc', 'contact.infoTitle', 'contact.sent', 'contact.hoursValue']);
const ROOT_TO_COMMON = { langSwitch: 'common.langSwitch', langLabel: 'common.langLabel', menu: 'common.menu', close: 'common.close' };

const flat = {};
const put = (key, lang, value) => ((flat[key] ||= { ar: '', en: '' })[lang] = value);
for (const lang of ['ar', 'en']) {
  for (const [ns, val] of Object.entries(dict[lang])) {
    if (SECTION_OWNED.has(ns)) continue;
    if (typeof val === 'string') put(ROOT_TO_COMMON[ns] || `common.${ns}`, lang, val);
    else for (const [k, v] of Object.entries(val)) if (!MOVED_KEYS.has(`${ns}.${k}`)) put(`${ns}.${k}`, lang, v);
  }
}
