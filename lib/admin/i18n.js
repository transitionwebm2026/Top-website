// Dashboard interface language (Arabic / English).
//
// - Component strings live in DICT and are read with `t('key', { vars })`.
// - Config objects (tabs, field schemas, options) carry inline `{ en, ar }`
//   labels and are read with `tr(value)`.
// The dashboard follows the same `tp-lang` cookie as the public site.

export const LOCALES = { en: 'en-GB', ar: 'ar-EG' };

/** `{ en, ar }` → the string for `lang`; plain strings pass through. */
export function tr(value, lang = 'en') {
  if (value && typeof value === 'object' && !Array.isArray(value) && ('en' in value || 'ar' in value)) {
    return value[lang] ?? value.en ?? '';
  }
  return value;
}

export function translate(lang, key, vars) {
  const s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
}

